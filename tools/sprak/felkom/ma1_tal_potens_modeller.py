def tal(n):
    return str(n).replace('-', '−')


def gpf(fore, efter, n0, n1, alts):
    """Talfaktorn går från fore till efter; exponenten ska gå från n0 till n1."""
    d = n1 - n0
    ggr = {1: '10', 2: '100', 3: '1 000'}[abs(d)]
    forkl = (f'Talfaktorn går från {fore} till {efter}, alltså {ggr} gånger {"mindre" if d > 0 else "större"}. '
             f'Då ska exponenten {"öka" if d > 0 else "minska"} med {abs(d)}, från {tal(n0)} till {tal(n1)}.')
    ut = []
    for e in alts:
        if e == n1:
            ut.append(None)
        elif e == n0:
            ut.append('Exponenten kan inte stå kvar när talfaktorn ändras. ' + forkl)
        elif (e - n0) * d < 0:
            ut.append('Exponenten ändras åt fel håll. ' + forkl)
        else:
            ut.append(forkl)
    return ut


