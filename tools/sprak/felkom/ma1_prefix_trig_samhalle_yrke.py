UPP = str.maketrans('-0123456789', '⁻⁰¹²³⁴⁵⁶⁷⁸⁹')
PREF = {'G': 9, 'M': 6, 'k': 3, '': 0, 'm': -3, 'µ': -6, 'n': -9}
NAMN = {'G': 'G', 'M': 'M', 'k': 'k', 'm': 'm', 'µ': 'µ', 'n': 'n'}


def pot(n):
    return '10' + str(n).translate(UPP)


def pf(ratt_pref, fel_pref, alts):
    """Det riktiga värdet har prefixet ratt_pref, men man skriver fel_pref. alts = [(exponent, 'stor'/'liten'), …]."""
    d = PREF[fel_pref] - PREF[ratt_pref]
    rikt = 'stort' if d > 0 else 'litet'
    a = f'{ratt_pref} = {pot(PREF[ratt_pref])}' if ratt_pref else ''
    b = f'{fel_pref} = {pot(PREF[fel_pref])}' if fel_pref else ''
    delar = ' och '.join(x for x in (a, b) if x)
    forkl = f'{delar}. Prefixen skiljer sig åt med faktorn {pot(abs(d))}, så värdet blir {pot(abs(d))} gånger för {rikt}.'
    ut = []
    for e, r in alts:
        if e == abs(d) and r == rikt[:4]:
            ut.append(None)
        elif e == abs(d):
            ut.append(f'Värdet blir för {rikt}, inte för {"litet" if rikt == "stort" else "stort"}. ' + forkl)
        else:
            ut.append(forkl)
    return ut


